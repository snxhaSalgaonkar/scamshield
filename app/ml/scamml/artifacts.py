"""Where artefacts and reports go, and how they are written."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
ASSETS = REPO / "app" / "app" / "src" / "main" / "assets" / "models"
GOLDEN = REPO / "app" / "app" / "src" / "test" / "resources" / "ml"
REPORTS = ROOT / "reports"


def write_model(path: Path, model: dict) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(model, separators=(",", ":"), ensure_ascii=False)
    path.write_text(body, encoding="utf-8")
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def _md_value(v) -> str:
    return json.dumps(v) if isinstance(v, (dict, list)) else str(v)


def write_report(name: str, report: dict) -> None:
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / f"{name}.json").write_text(json.dumps(report, indent=2))
    lines = [f"# {name} report", "", "Generated by the training script; do not edit by hand.", ""]

    def walk(d: dict, depth: int):
        for k, v in d.items():
            if isinstance(v, dict) and k not in ("confusion_matrix",):
                lines.append(f"{'#' * min(depth + 2, 6)} {k}")
                lines.append("")
                walk(v, depth + 1)
                lines.append("")
            elif k == "calibration":
                lines.append("| predicted range | n | mean predicted | observed |")
                lines.append("|---|---|---|---|")
                for b in v:
                    lines.append(f"| {b['range'][0]}-{b['range'][1]} | {b['n']} | {b['mean_predicted']} | {b['observed_rate']} |")
            else:
                lines.append(f"- **{k}**: {_md_value(v)}")

    walk(report, 0)
    (REPORTS / f"{name}.md").write_text("\n".join(lines) + "\n")
